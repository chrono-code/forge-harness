#!/usr/bin/env bash
# 정지 가드 — 「규약을 붙였더니 모델이 부재를 못 말하게 됐나」.
#
# 🟥 왜 코드인가 (2026-09-01): 이 판정은 그날까지 **저자가 손으로** 했다. 저자가 자기 실험의
#    정지선을 자기가 적용하는 형태는 오늘 코퍼스가 반복해서 지목한 실패 모드다. 산술이 틀릴까
#    봐가 아니라, **관대하게 적용될까 봐** 기계로 옮긴다.
# 🟥 그리고 옮기는 순간 «가드가 실제로 무는가» 를 known-pair 로 물을 수 있게 된다 —
#    산문 가드는 그 질문 자체가 성립하지 않는다(레인이 초록인 이유 셋 중 ③을 못 배제).
#
# 사용: delta_guard.sh <기준.tsv> <처치.tsv> [임계 %p, 기본 10] [기대 항목수]
#   🟥 기대 항목수를 주면 «분모가 그 값인가» 를 먼저 본다. 2026-09-01 실측:
#      LLM 배치 채점이 **같은 입력에서** 96건 중 1건을 통째로 빠뜨린다(판정은 결정적,
#      «출력 완결성»이 비결정). 누락을 안 보면 분모가 조용히 줄고 기권률이 움직인다.
#      🟥 누락은 «오분류»가 아니라 **미측정**이다 — 0 으로도 통과로도 접지 않는다.
#   입력 = 채점 결과. 각 줄 `<id><TAB><REFUSED|ANSWERED|OTHER>`
#   0 = 통과 · 3 = 정지(임계 초과) · 4 = 판정불가(분모 결손) · 2 = 인자오류
#
# 🟥 방향 무관이다. 천장 보정도 없다 — 보정은 새 자유도이고, 자유도는 저자 쪽으로 휜다.
set -uo pipefail

A="${1:-}"; B="${2:-}"; LIM="${3:-10}"; EXP="${4:-}"
[ -n "$A" ] && [ -n "$B" ] || { echo "usage: delta_guard.sh <baseline.tsv> <arm.tsv> [threshold_pp]" >&2; exit 2; }
for f in "$A" "$B"; do
  [ -f "$f" ] || { echo "🟥 없다: $f — «없음»은 «비었음»이 아니다. 판정하지 않는다" >&2; exit 4; }
done
case "$LIM" in ''|*[!0-9]*) echo "🟥 임계는 정수 %p 여야 한다: $LIM" >&2; exit 2 ;; esac

# 🟥 분자와 분모를 «둘 다» 낸다. 오늘 세 번, 검출기는 성실함이 아니라 분모였다.
_tally() { # $1=파일 → "refused total"
  LC_ALL=C awk -F'\t' '
    NF>=2 { t++; if ($2 ~ /^REFUSED[[:space:]]*$/) r++ }
    END { printf "%d %d", r+0, t+0 }
  ' "$1"
}
read -r RA TA <<<"$(_tally "$A")"
read -r RB TB <<<"$(_tally "$B")"

echo "기준  $A : REFUSED $RA / $TA"
echo "처치  $B : REFUSED $RB / $TB"

# 🟥 분모 0 은 «기권률 0%» 가 아니라 «측정 없음» 이다. 통과로 접지 않는다.
if [ "$TA" -eq 0 ] || [ "$TB" -eq 0 ]; then
  echo "🟥 판정불가 — 분모가 0 인 쪽이 있다(기준 $TA · 처치 $TB). 통과 아님." >&2
  exit 4
fi

# 🟥 분모 «결손» — 0 이 아니라 «기대보다 적음». 이게 진짜 흔한 얼굴이다.
if [ -n "$EXP" ]; then
  case "$EXP" in ''|*[!0-9]*) echo "🟥 기대 항목수는 정수여야 한다: $EXP" >&2; exit 2 ;; esac
  if [ "$TA" -ne "$EXP" ] || [ "$TB" -ne "$EXP" ]; then
    echo "🟥 판정불가 — 분모가 기대와 다르다(기대 $EXP · 기준 $TA · 처치 $TB)." >&2
    echo "   빠진 항목은 «오답»이 아니라 **미측정**이다. 재실행하거나 UNMEASURED 로 명시해라." >&2
    exit 4
  fi
fi

# 정수 %p 로 소수 1자리까지 (bash 산술만 — bc 의존 없음)
_pct10() { echo $(( $1 * 1000 / $2 )); }   # 0.1%p 단위
PA=$(_pct10 "$RA" "$TA"); PB=$(_pct10 "$RB" "$TB")
D=$(( PA - PB )); [ "$D" -lt 0 ] && D=$(( -D ))
LIM10=$(( LIM * 10 ))

printf '기권률  기준 %d.%d%%  처치 %d.%d%%  |Δ| %d.%d%%p  (임계 %d%%p)\n' \
  $(( PA / 10 )) $(( PA % 10 )) $(( PB / 10 )) $(( PB % 10 )) $(( D / 10 )) $(( D % 10 )) "$LIM"

if [ "$D" -gt "$LIM10" ]; then
  echo "🟥 정지 — |Δ| 가 임계를 넘었다. 이 회차는 폐기다(방향 무관)." >&2
  echo "   🟥 문구를 고쳐 재시도하지 «않는다». 사전등록이 그렇게 적혀 있다." >&2
  exit 3
fi
echo "🟢 통과 — 가드가 물지 않았다."
